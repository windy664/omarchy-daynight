//! The configuration file and the paths the tool owns.

use chrono_tz::Tz;
use std::path::PathBuf;

use crate::solar::system_timezone;

pub const PROGRAM_NAME: &str = "omarchy-daynight";

pub fn config_dir() -> PathBuf {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| home().join(".config"));
    base.join(PROGRAM_NAME)
}

pub fn config_file() -> PathBuf {
    config_dir().join("config")
}

pub fn state_dir() -> PathBuf {
    let base = std::env::var_os("XDG_STATE_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| home().join(".local/state"));
    base.join(PROGRAM_NAME)
}

pub fn pause_file() -> PathBuf {
    state_dir().join("pause")
}

pub fn home() -> PathBuf {
    std::env::var_os("HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("/"))
}

pub fn unit_dir() -> PathBuf {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| home().join(".config"));
    base.join("systemd/user")
}

pub fn current_theme_file() -> PathBuf {
    let base = std::env::var_os("XDG_STATE_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| home().join(".local/state"));
    base.join("omarchy/current/theme.name")
}

#[derive(Debug, Clone)]
pub struct Config {
    pub day_theme: String,
    pub night_theme: String,
    pub latitude: Option<f64>,
    pub longitude: Option<f64>,
    pub timezone: Option<String>,
    pub auto_locate: bool,
    pub dawn_offset: i32,
    pub dusk_offset: i32,
    pub precise_schedule: bool,
    pub poll_interval: String,
    pub fallback_interval: String,
    pub fallback_day_start: String,
    pub fallback_night_start: String,
    pub nightlight: String,
    pub on_switch: String,
}

impl Default for Config {
    fn default() -> Self {
        Config {
            day_theme: "catppuccin-latte".into(),
            night_theme: "catppuccin".into(),
            latitude: None,
            longitude: None,
            timezone: None,
            auto_locate: false,
            dawn_offset: 0,
            dusk_offset: 0,
            precise_schedule: true,
            poll_interval: "10min".into(),
            fallback_interval: "6h".into(),
            fallback_day_start: "07:00".into(),
            fallback_night_start: "19:00".into(),
            nightlight: "off".into(),
            on_switch: String::new(),
        }
    }
}

impl Config {
    pub fn load() -> Config {
        let mut config = Config::default();
        let Ok(text) = std::fs::read_to_string(config_file()) else {
            return config;
        };

        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };
            let value = unquote(value.trim());
            match key.trim() {
                "day_theme" => config.day_theme = value,
                "night_theme" => config.night_theme = value,
                "latitude" => config.latitude = value.parse().ok(),
                "longitude" => config.longitude = value.parse().ok(),
                "timezone" => config.timezone = if value.is_empty() { None } else { Some(value) },
                "auto_locate" => config.auto_locate = value == "1" || value == "true",
                "dawn_offset" => config.dawn_offset = value.parse().unwrap_or(0),
                "dusk_offset" => config.dusk_offset = value.parse().unwrap_or(0),
                "precise_schedule" => config.precise_schedule = value == "1" || value == "true",
                "poll_interval" => config.poll_interval = value,
                "fallback_interval" => config.fallback_interval = value,
                "fallback_day_start" => config.fallback_day_start = value,
                "fallback_night_start" => config.fallback_night_start = value,
                "nightlight" => config.nightlight = value,
                "on_switch" => config.on_switch = value,
                _ => {}
            }
        }

        config
    }

    pub fn save(&self) -> std::io::Result<()> {
        let dir = config_dir();
        std::fs::create_dir_all(&dir)?;

        let latitude = self.latitude.map(|v| format!("{v}")).unwrap_or_default();
        let longitude = self.longitude.map(|v| format!("{v}")).unwrap_or_default();
        let timezone = self.timezone.clone().unwrap_or_default();

        let text = format!(
            r#"# {PROGRAM_NAME} configuration
# Generated by "{PROGRAM_NAME} install". Edit freely; it is read on every run.

# Theme applied between sunrise and sunset, and between sunset and sunrise.
day_theme={day_theme}
night_theme={night_theme}

# Where you are. Leave empty and run "{PROGRAM_NAME} locate" to fill them in.
latitude={latitude}
longitude={longitude}
# Empty means: take the timezone from the system.
timezone={timezone}

# Set to 1 to look up the coordinates over the network on every run.
auto_locate={auto_locate}

# Shift the switch by minutes: negative switches earlier, positive later.
dawn_offset={dawn_offset}
dusk_offset={dusk_offset}

# Precise scheduling: 1 = also arm one-shot timers that fire exactly at
# sunrise and sunset. 0 = rely on the poll timer alone.
precise_schedule={precise_schedule}

# How often the timer checks whether the phase changed. This is the only
# thing that runs when precise_schedule is 0, so keep it short.
poll_interval={poll_interval}

# How often the fallback timer checks when precise_schedule is 1. The exact
# timers do the work then, and this only covers a switch that was missed
# while the machine was asleep, so a long interval is fine.
fallback_interval={fallback_interval}

# Used only inside the polar circles, where the sun may never rise or set.
fallback_day_start={fallback_day_start}
fallback_night_start={fallback_night_start}

# Night light (hyprsunset) handling: off, auto.
nightlight={nightlight}

# Optional command run after every theme change. It has to be quoted, since
# the config file is read by sourcing it.
on_switch="{on_switch}"
"#,
            day_theme = self.day_theme,
            night_theme = self.night_theme,
            latitude = latitude,
            longitude = longitude,
            timezone = timezone,
            auto_locate = if self.auto_locate { 1 } else { 0 },
            dawn_offset = self.dawn_offset,
            dusk_offset = self.dusk_offset,
            precise_schedule = if self.precise_schedule { 1 } else { 0 },
            poll_interval = self.poll_interval,
            fallback_interval = self.fallback_interval,
            fallback_day_start = self.fallback_day_start,
            fallback_night_start = self.fallback_night_start,
            nightlight = self.nightlight,
            on_switch = self.on_switch,
        );

        std::fs::write(config_file(), text)?;
        set_private_permissions(&config_file());
        Ok(())
    }

    /// The timezone to compute in: the one from the config, or the system's.
    pub fn resolve_timezone(&self) -> Tz {
        if let Some(name) = &self.timezone
            && let Ok(tz) = name.parse::<Tz>()
        {
            return tz;
        }
        system_timezone().unwrap_or_else(|| "UTC".parse().unwrap())
    }

    pub fn timezone_label(&self) -> String {
        self.resolve_timezone().name().to_string()
    }
}

fn unquote(value: &str) -> String {
    let trimmed = value.trim();
    if trimmed.len() >= 2 {
        let bytes = trimmed.as_bytes();
        if (bytes[0] == b'"' && bytes[bytes.len() - 1] == b'"')
            || (bytes[0] == b'\'' && bytes[bytes.len() - 1] == b'\'')
        {
            return trimmed[1..trimmed.len() - 1].to_string();
        }
    }
    trimmed.to_string()
}

fn set_private_permissions(path: &std::path::Path) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600));
    }
}
